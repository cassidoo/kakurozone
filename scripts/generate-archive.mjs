import { mkdir, writeFile } from 'node:fs/promises'
import { createServer } from 'vite'

const server = await createServer({
  server: { middlewareMode: true }, appType: 'custom', cacheDir: 'node_modules/.vite-archive',
})
try {
  const { generateDailyPuzzle, validatePuzzleStructure, countSolutions } =
    await server.ssrLoadModule('/src/engine/index.ts')
  const puzzles = []
  const fingerprints = new Set()
  const anchor = Date.UTC(2026, 8, 20)
  for (let index = 0; index < 300; index += 1) {
    const seed = new Date(anchor - index * 86_400_000).toISOString().slice(0, 10)
    const start = performance.now()
    const puzzle = generateDailyPuzzle(seed)
    const errors = validatePuzzleStructure(puzzle)
    if (errors.length || countSolutions(puzzle) !== 1) {
      throw new Error(`Invalid archive puzzle ${seed}: ${errors.join(', ')}`)
    }
    const fingerprint = JSON.stringify(puzzle.cells.map((row) => row.map((cell) =>
      cell.kind === 'play' ? '.' : cell.clue ?? '#',
    )))
    if (fingerprints.has(fingerprint)) throw new Error(`Duplicate puzzle ${seed}`)
    fingerprints.add(fingerprint)
    puzzles.push(puzzle)
    console.log(`${index + 1}/300 ${seed} ${puzzle.metadata.difficulty} ${(performance.now() - start).toFixed(0)}ms`)
  }
  for (const difficulty of ['Easy', 'Medium', 'Hard']) {
    if (puzzles.filter((puzzle) => puzzle.metadata.difficulty === difficulty).length !== 100) {
      throw new Error(`Expected exactly 100 ${difficulty} puzzles`)
    }
  }
  await mkdir(new URL('../src/data/', import.meta.url), { recursive: true })
  await writeFile(
    new URL('../src/data/archive.ts', import.meta.url),
    `import type { KakuroPuzzle } from '../engine/types'\n\n// Generated by npm run generate:archive; published puzzle definitions remain stable.\nexport const archivePuzzles: readonly KakuroPuzzle[] = ${JSON.stringify(puzzles)}\n`,
  )
} finally {
  await server.close()
}
